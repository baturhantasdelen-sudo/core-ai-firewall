function resetAgentRuntime(agentId: string): void {
  resetKillSwitchState(agentId);
  resetCapabilityRevocation(agentId);
  resetTrajectory(agentId);
}

/**
 * Runs continuous red team simulation against agent security posture.
 */
export function runRedTeamSimulation(input: RedTeamSimulationInput): SimulationResult {
  const scenarios = [
    ...PREDEFINED_SCENARIOS,
    ...(input.scenarios ?? []),
    ...buildAutoScenarios(input.agentId),
  ];

  const outcomes: VectorSimulationOutcome[] = scenarios.map((scenario) => {
    resetAgentRuntime(input.agentId);

    const evaluation = evaluateAgentAction({
      agentId: input.agentId,
      userIntent: scenario.userIntent,
      toolCall: { name: scenario.toolName, args: scenario.toolArgs },
      agentCapabilities: input.capabilities,
    });

    const blocked = evaluation.decision !== 'ALLOW';

    return {
      scenarioId: scenario.id,
      attackVector: scenario.attackVector,
      blocked,
      payload: formatPayload(scenario),
      response: formatResponse(evaluation.decision, evaluation.violations, evaluation.riskScore),
      riskScore: evaluation.riskScore,
      vulnerability: blocked
        ? undefined
        : `${scenario.attackVector}: agent permitted ${scenario.toolName} under attack scenario "${scenario.name}"`,
    };
  });

  const blockedCount = outcomes.filter((outcome) => outcome.blocked).length;
  const exposedCount = outcomes.length - blockedCount;
  const resilienceScore = Math.round((blockedCount / outcomes.length) * 100);
  const vulnerabilities = outcomes
    .filter((outcome) => !outcome.blocked && outcome.vulnerability)
    .map((outcome) => outcome.vulnerability!);

  const result: SimulationResult = {
    simulationId: generateSimulationId(),
    agentId: input.agentId,
    agentName: input.agentName,
    resilienceScore,
    riskRating: deriveRiskRating(resilienceScore),
    outcomes,
    vulnerabilities,
    blockedCount,
    exposedCount,
    timestamp: new Date().toISOString(),
  };

  simulationStore.set(result.simulationId, result);
  return result;
}

/**
 * Simulates auto-remediation for exposed attack vectors.
 */
export function autoRemediateVulnerabilities(simulationId: string): AutoRemediateResult {
  const simulation = simulationStore.get(simulationId);
  if (!simulation) {
    return {
      simulationId,
      remediated: [],
      remainingVulnerabilities: [],
      resilienceScoreAfter: 0,
    };
  }

  const remediated = simulation.vulnerabilities.map(
    (vulnerability) => `PATCHED: ${vulnerability.split(':')[0]} — policy rule tightened`,
  );

  simulation.remediated = remediated;
  simulation.resilienceScore = Math.min(100, simulation.resilienceScore + simulation.exposedCount * 15);
  simulation.riskRating = deriveRiskRating(simulation.resilienceScore);
  simulation.vulnerabilities = [];

  return {
    simulationId,
    remediated,
    remainingVulnerabilities: [],
    resilienceScoreAfter: simulation.resilienceScore,
  };
}

export function getRedTeamSimulation(simulationId: string): SimulationResult | undefined {
  const simulation = simulationStore.get(simulationId);
  return simulation ? { ...simulation } : undefined;
}

export function listPredefinedScenarios(): RedTeamScenario[] {
  return PREDEFINED_SCENARIOS.map((scenario) => ({ ...scenario }));
}

export function resetRedTeamStore(): void {
  simulationStore.clear();
}
